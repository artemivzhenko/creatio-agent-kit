"""The baseline test cases of a package, written from what the describe layer knows about its schemas (S27-T02).

    cases_from_package(package, out, env=None) -> [report line]

Into the project's layout `<out>/<Package>/` (S51; `out` = `<workspace>/tests`): `integration/<Object>.act` for an own object (insert,
read, update, delete over OData), `integration/<Process>.act` + `integration/<Process>.json` for a process without a user task,
`pages/<Page>.json` + `e2e/<Page>.act` for a Freedom UI form page of an own object (`layout="root"`: the test utility's own root,
`Cases/<Package>/`, `ProcessCases/<Package>/`, `Configuration/...`, for the merge campaign). Every case carries a `# schema: <Name>` line.
`coverage_report(package, out)` counts, per schema of the package, the cases in `unit/`, `integration/` and `e2e/`.
Everything else is listed as `not generated: ...`; a value or a field that cannot be guessed is a `# stop:` line in the case
(and its report line), never a guess. A generated file starts with `HEADER`; a second run rewrites only the files that still
carry it, so an edited case is kept.
"""

from __future__ import annotations

import json
import re
from datetime import date
from pathlib import Path

from .describe.registry import _is_freedom_page
from .entity.catalog import column_flags
from .entity.schema import EntitySchema
from .files import ALL_DATA_VALUE_TYPES
from .page.schema import PageSchema
from .process.catalog import DIRECTION, short_type
from .process.schema import ProcessSchema

HEADER = "# generated by cases-from-package {day}; review before running"
HEADER_START = "# generated by cases-from-package"
SYSTEM = {"Id", "CreatedOn", "CreatedBy", "ModifiedOn", "ModifiedBy", "ProcessListeners"}
OWN_PARENTS = {"BaseEntity", "BaseLookup"}
TEXT = {"ShortText": 50, "MediumText": 250, "LongText": 500, "Text": 500, "MaxSizeText": 500}
FIXED = {"Integer": "1", "Float": "100", "Float0": "100", "Float1": "100", "Float2": "100", "Float3": "100", "Float4": "100", "Float8": "100",
         "Money": "100", "Money0": "100", "Money1": "100", "Money3": "100", "Boolean": "false", "PhoneText": "+15551230000",
         "WebText": "https://example.com", "Time": "12:00:00"}
UPDATED = {"Integer": "2", "Money": "200", "Float2": "200", "Boolean": "true"}  # a second value that differs from FIXED


class Stop(Exception):
    """A value or a field the generator will not guess; the message is the stop line."""


def sample(column: dict, type_name: str, env=None, looked: dict | None = None, second: bool = False, ref: str | None = None) -> str:
    """A typed sample value for a column (text with the column name and a stamp, 1, 100, false, today, the first row of the lookup)."""
    name = column["A2"]
    stamp = date.today().strftime("%y%m%d")
    if type_name in TEXT:
        return (f"{name}{stamp}{'u' if second else ''}")[:TEXT[type_name]]
    if type_name == "EmailText":
        return f"test{stamp}{'u' if second else ''}@example.com"
    if type_name in FIXED:
        return UPDATED.get(type_name, FIXED[type_name]) if second else FIXED[type_name]
    if type_name == "Date":
        return date.today().isoformat()
    if type_name == "DateTime":
        return date.today().isoformat() + "T12:00:00Z"
    if type_name in ("Lookup", "ImageLookup"):
        if env is None:
            raise Stop(f"lookup {name}: no value - give --env or edit")
        looked = looked if looked is not None else {}
        if not ref:
            raise Stop(f"lookup {name}: the object it points at is unknown - edit")
        if ref not in looked:
            try:
                rows = env.odata(ref, ["Id"], None, 1)
            except (RuntimeError, KeyError, ValueError, OSError) as e:
                raise Stop(f"lookup {name}: reading {ref} failed ({e}) - edit") from e
            looked[ref] = rows[0]["Id"] if rows else None
        if not looked[ref]:
            raise Stop(f"lookup {name}: {ref} has no row - add one or edit")
        return str(looked[ref])
    raise Stop(f"column {name}: no sample value for type {type_name} - edit")


def _type(column: dict) -> str:
    return ALL_DATA_VALUE_TYPES.get(column.get("S2"), str(column.get("S2")))


def _ref(entity: EntitySchema, column: dict) -> str | None:
    return entity.ref_name(column["S4"]) if column.get("S4") else None


def _pairs(columns: list[tuple[str, str]]) -> str:
    return ";".join(f"{c}={v}" for c, v in columns)


def _dest(layout: str, out: Path, pkg: str, kind: str, name: str) -> Path:
    """Where a generated file goes; kind: object | process | process-config | page | page-case."""
    if layout == "root":
        sub = {"object": ("Cases", pkg, ".act"), "process": ("ProcessCases", pkg, ".act"), "process-config": ("Configuration", "processes", ".json"),
               "page": ("Configuration", "pages", ".json"), "page-case": ("Cases", pkg, ".act")}[kind]
        return out / sub[0] / sub[1] / (name + sub[2])
    folder, ext = {"object": ("integration", ".act"), "process": ("integration", ".act"), "process-config": ("integration", ".json"),
                   "page": ("pages", ".json"), "page-case": ("e2e", ".act")}[kind]
    return out / pkg / folder / (name + ext)


def tests_root(project: Path | str) -> Path:
    """`<package.workspace>/tests` of a project.json (a relative workspace is relative to the file)."""
    file = Path(project)
    ws = (json.loads(file.read_text(encoding="utf-8-sig")).get("package") or {}).get("workspace")
    if not isinstance(ws, str) or not ws.strip():
        raise ValueError("project.json has no package.workspace: give --out")
    return (file.resolve().parent / ws) / "tests"


def _tag(text: str, name: str) -> str:
    """`# schema: <name>` right after the generated header: the line the coverage report counts."""
    return text.replace("\n", f"\n# schema: {name}\n", 1)


def _write(path: Path, text: str, report: list[str], out: Path) -> None:
    rel = path.relative_to(out).as_posix()
    if path.is_file():
        first = path.read_text(encoding="utf-8-sig").splitlines()[:1]
        if path.suffix == ".json":
            if path.read_text(encoding="utf-8") != text:
                report.append(f"kept {rel} (exists and differs; delete it to regenerate)")
            else:
                report.append(f"same {rel}")
            return
        if not (first and first[0].startswith(HEADER_START)):
            report.append(f"kept {rel} (edited: no generated header)")
            return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    report.append(f"wrote {rel}")


def object_case(entity: EntitySchema, user: str, env=None, looked: dict | None = None) -> tuple[str, list[str]]:
    """(case text, stop lines) of an own object: insert the required columns, read the row back, update one column, read it, delete."""
    name = entity.name
    stops, required = [], []
    for c in entity.columns():
        if c["A2"] in SYSTEM:
            continue
        if "required" in column_flags(c) and not isinstance(c.get("E12"), dict):  # a default fills a required column itself
            try:
                required.append((c["A2"], sample(c, _type(c), env, looked, ref=_ref(entity, c))))
            except Stop as e:
                stops.append(str(e))
    editable = [c for c in entity.own_columns() if c["A2"] not in SYSTEM and "required" not in column_flags(c)]
    chosen = None
    for c in editable:
        if _type(c) in TEXT or _type(c) in UPDATED:
            chosen = c
            break
    if not required and chosen is not None:  # an insert needs one column
        required.append((chosen["A2"], sample(chosen, _type(chosen))))
    lines = [HEADER.format(day=date.today().isoformat()), "# writes", f"# {name}: insert, read back, update, read back, delete over OData", "", f"use {user}"]
    if stops or not required:
        lines += [f"# stop: {s}" for s in stops] or [f"# stop: {name} has no column a sample can be written to - edit"]
        return "\n".join(lines) + "\n", stops or [f"{name}: no column a sample can be written to"]
    lines += [f"insert {name} as R set {_pairs(required)}", f"check-record {name} Id=$R exists"]
    if chosen is not None:
        value = sample(chosen, _type(chosen), second=True)
        lines += [f"update {name} $R set {chosen['A2']}={value}", f"check-record {name} Id=$R has {chosen['A2']} eq {value}"]
    lines += [f"delete {name} $R"]
    return "\n".join(lines) + "\n", []


def process_case(process: ProcessSchema, user: str, env=None, looked: dict | None = None) -> str:
    """The process case: start (with samples for the simple input parameters), then `check-result <out> exists` per output."""
    ins, outs = [], []
    for p in process.params:
        direction = DIRECTION.get(p.get("L12", 0), "Variable")
        if direction == "Out":
            outs.append(p["A2"])
        elif direction == "In":
            column = {"A2": p["A2"], "S2": p.get("L1")}
            try:
                ins.append((p["A2"], sample(column, ALL_DATA_VALUE_TYPES.get(p.get("L1"), ""), env, looked)))
            except Stop:
                continue  # a parameter we cannot make a value for keeps the process's default
    lines = [HEADER.format(day=date.today().isoformat()), f"# {process.name}: start it and read its outputs", "", f"use {user}",
             f"start {process.name}" + (f" with {_pairs(ins)}" if ins else "")]
    lines += [f"check-result {o} exists" for o in outs]
    return "\n".join(lines) + "\n"


def page_case(page: PageSchema, entity: EntitySchema | None, name: str, user: str, page_file: dict, env=None, looked: dict | None = None) -> tuple[str, list[str]]:
    """A new record on the form page: fill the required columns the page shows, save, find the row over OData, delete it."""
    codes = {e["code"]: e for e in page_file["elements"]}
    head = [HEADER.format(day=date.today().isoformat()), "# writes", f"# {page.name}: a new record through the form", "", f"use {user}"]
    if entity is None:
        return "\n".join(head + [f"# stop: the object of {page.name} is not an own object of this package - edit"]) + "\n", ["the page's object is not in the package"]
    sets, stops = [], []
    for c in entity.columns():
        if c["A2"] in SYSTEM or "required" not in column_flags(c) or isinstance(c.get("E12"), dict):
            continue
        element = codes.get(c["A2"])
        if element is None:
            stops.append(f"required column {c['A2']} is not an element of {page.name}")
            continue
        if element["type"] not in ("Text", "Integer", "Decimal", "Email", "Phone", "Date", "DateTime", "Boolean"):
            stops.append(f"required column {c['A2']} is a {element['type']} on the page - edit")
            continue
        try:
            sets.append((c["A2"], sample(c, _type(c), env, looked, ref=_ref(entity, c))))
        except Stop as e:
            stops.append(str(e))
    if "SaveButton" not in codes:
        stops.append(f"{page.name} has no SaveButton element")
    if stops or not sets:
        return "\n".join(head + [f"# stop: {s}" for s in stops or ["no required column to fill"]]) + "\n", stops or ["no required column to fill"]
    display = next((c["A2"] for c in entity.columns() if c["UId"] == (entity.effective or {}).get("D4")), sets[0][0])
    key = display if display in dict(sets) else sets[0][0]
    lines = head + [f"open {name}"]
    lines += [f'set {c} "{v}"' if codes[c]["type"] not in ("Integer", "Decimal", "Boolean") else f"set {c} {v}" for c, v in sets]
    lines += ["click SaveButton", f"check-record {entity.name} {key}={dict(sets)[key]} exists", f"delete-record {entity.name} {key}={dict(sets)[key]}"]
    return "\n".join(lines) + "\n", []


def _manager(folder: Path) -> tuple[str, dict]:
    data = json.loads((folder / "descriptor.json").read_text(encoding="utf-8-sig"))["Descriptor"]
    return data.get("ManagerName", ""), data


def cases_from_package(package: Path | str, out: Path | str, env=None, user: str = "Supervisor", layout: str = "project") -> list[str]:
    """Write the cases; returns one report line per file or schema (`wrote`, `same`, `kept`, `stop`, `not generated`)."""
    package, out = Path(package), Path(out)
    pkg = package.name
    report: list[str] = []
    looked: dict = {}
    folders = sorted(d for d in (package / "Schemas").glob("*") if (d / "descriptor.json").is_file()) if (package / "Schemas").is_dir() else []
    entities = {}
    for d in folders:
        manager, data = _manager(d)
        if manager == "EntitySchemaManager" and not data.get("ExtendParent"):
            entities[d.name] = EntitySchema(package, d.name)
    for d in folders:
        manager, data = _manager(d)
        name = d.name
        try:
            if manager == "EntitySchemaManager":
                if data.get("ExtendParent"):
                    report.append(f"not generated: object {name} replaces another object - its cases belong to the package that owns it")
                    continue
                e = entities[name]
                if e.parent_name not in OWN_PARENTS:
                    report.append(f"not generated: object {name} (parent {e.parent_name})")
                    continue
                if (e.effective or {}).get("D1") or (e.effective or {}).get("D10"):
                    report.append(f"not generated: object {name} is virtual or a view")
                    continue
                text, stops = object_case(e, user, env, looked)
                report += [f"stop {name}: {s}" for s in stops]
                _write(_dest(layout, out, pkg, "object", name), _tag(text, name), report, out)
            elif manager == "ProcessSchemaManager":
                proc = ProcessSchema(package, name)
                if any(short_type(el).startswith("ProcessSchemaUserTask") for el in proc.elements):
                    report.append(f"not generated: process {name} has a user task")
                    continue
                if not any(short_type(el) == "ProcessSchemaStartEvent" for el in proc.elements):
                    report.append(f"not generated: process {name} starts only by an event (signal, timer, message): it cannot be started manually")
                    continue
                _write(_dest(layout, out, pkg, "process-config", name), json.dumps(proc.test_config(), indent=2, ensure_ascii=False) + "\n", report, out)
                _write(_dest(layout, out, pkg, "process", name), _tag(process_case(proc, user, env, looked), name), report, out)
            elif manager == "ClientUnitSchemaManager" and not _is_freedom_page(package, name):
                report.append(f"not generated: Classic page {name} - see S28-T04")
            elif manager == "ClientUnitSchemaManager" and name.endswith("_FormPage"):
                page = PageSchema(package, name)
                base = name[: -len("_FormPage")]
                page_name = base + "Form"
                page_file, _ = page.page_file(page_name)
                if not any(e["code"] == "SaveButton" for e in page_file["elements"]):  # the template does not list it; every form page has it once changed
                    page_file["elements"].append({"code": "SaveButton", "label": "Save", "type": "Button", "pinned": True})
                text, stops = page_case(page, entities.get(base), page_name, user, page_file, env, looked)
                report += [f"stop {name}: {s}" for s in stops]
                _write(_dest(layout, out, pkg, "page", page_name), json.dumps(page_file, indent=2, ensure_ascii=False) + "\n", report, out)
                _write(_dest(layout, out, pkg, "page-case", name), _tag(text, name), report, out)
            elif manager == "ClientUnitSchemaManager":
                report.append(f"not generated: page {name} (not a form page)")
        except (KeyError, ValueError, OSError) as e:
            report.append(f"stop {name}: {type(e).__name__}: {e.args[0] if e.args else e}")
    return report


KINDS = {"EntitySchemaManager": "object", "ProcessSchemaManager": "process", "ClientUnitSchemaManager": "page"}
TIERS = ("unit", "integration", "e2e")


def coverage_report(package: Path | str, out: Path | str) -> list[str]:
    """One line per schema and `Files/cs` class of the package (`<Schema> (<kind>): unit n | integration n | e2e n`), then
    `not covered: ...` for every one with 0, then `covered N of M`. A case counts for the names in its `# schema:` lines (`// schema:`
    in a .cs file) and for its file name (`<Class>Tests.cs` names `<Class>`)."""
    package, tests = Path(package), Path(out) / Path(package).name
    schemas = {}
    for d in sorted((package / "Schemas").glob("*")) if (package / "Schemas").is_dir() else []:
        if (d / "descriptor.json").is_file() and (kind := KINDS.get(_manager(d)[0])):
            schemas[d.name] = kind
    for f in sorted((package / "Files" / "cs").rglob("*.cs")) if (package / "Files" / "cs").is_dir() else []:
        schemas.setdefault(f.stem, "class")
    counts = {n: dict.fromkeys(TIERS, 0) for n in schemas}
    for tier in TIERS:
        for f in sorted((tests / tier).rglob("*")) if (tests / tier).is_dir() else []:
            if f.suffix not in (".act", ".cs"):
                continue
            names = {f.stem[:-5] if f.suffix == ".cs" and f.stem.endswith("Tests") else f.stem}
            for line in f.read_text(encoding="utf-8-sig", errors="replace").splitlines():
                m = re.match(r"\s*(?:#|//)\s*schema:\s*(.+)", line)
                if m:
                    names.update(n.strip() for n in m.group(1).split(","))
            for n in names & counts.keys():
                counts[n][tier] += 1
    lines = [f"{n} ({schemas[n]}): " + " | ".join(f"{t} {counts[n][t]}" for t in TIERS) for n in schemas]
    missing = [n for n in schemas if not any(counts[n].values())]
    lines += [f"not covered: {n} ({schemas[n]})" for n in missing]
    return lines + [f"covered {len(schemas) - len(missing)} of {len(schemas)}"]
