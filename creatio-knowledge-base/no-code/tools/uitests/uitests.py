#!/usr/bin/env python3
"""The baseline test cases of a package, written from its schemas (library: ../creatio_schemas/cases.py).

    python uitests.py cases-from-package <package> (--out <tests folder> | --project <project.json>) [--env <env>] [--user Supervisor] [--report]

Writes into <tests folder> (default <package.workspace>/tests of the project): <Package>/integration/<Object>.act (insert, read, update,
delete over OData) for an own object, <Package>/integration/<Process>.act + .json for a process without a user task,
<Package>/pages/<Page>.json + <Package>/e2e/<Page>.act for a Freedom UI form page. `--report` writes nothing and prints the coverage: per
schema `unit n | integration n | e2e n`, `not covered: <Schema> (<kind>)`, `covered N of M`. A value or a field the generator will not
guess is a `# stop:` line in the case and a `stop` line here; `--env` lets a lookup take the first row of its object over OData.
A generated file starts with `# generated by cases-from-package`; a second run rewrites only files that still carry it.
Exit 1 when any `stop` was reported, 2 on a usage error.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="command", required=True)
    c = sub.add_parser("cases-from-package", help="write the baseline cases of a package into <out>/<Package>/{integration,e2e,pages}, or --report the coverage")
    c.add_argument("package")
    c.add_argument("--out", help="the tests folder (default: <package.workspace>/tests of --project)")
    c.add_argument("--report", action="store_true", help="write nothing: per schema the cases in unit/integration/e2e, then `not covered` lines")
    c.add_argument("-e", "--env", help="clio environment name: lookups take the first row of their object")
    c.add_argument("--project", help="project.json holding the environment")
    c.add_argument("--user", default="Supervisor", help="the user the cases `use` (default Supervisor)")
    args = p.parse_args(argv)
    from creatio_schemas.cases import cases_from_package, coverage_report, tests_root
    from creatio_schemas.environment import open_environment
    try:
        out = args.out or (tests_root(args.project) if args.project else None)
        if out is None:
            raise ValueError("give --out or --project")
        if args.report:
            print("\n".join(coverage_report(args.package, out)))
            return 0
        env = open_environment(args.env, args.project) if args.env or args.project else None
        report = cases_from_package(args.package, out, env, args.user)
    except (OSError, KeyError, ValueError, RuntimeError) as e:
        print(f"error: {e.args[0] if e.args else e}", file=sys.stderr)
        return 2
    print("\n".join(report) if report else "(no schema to write cases for)")
    return 1 if any(line.startswith("stop") for line in report) else 0


if __name__ == "__main__":
    for _stream in (sys.stdout, sys.stderr):  # S33-T09: a Cyrillic caption must not need PYTHONIOENCODING
        if hasattr(_stream, "reconfigure"):
            _stream.reconfigure(encoding="utf-8")
    sys.exit(main())
